use std::{
    fs,
    io::Write,
    path::{Component, Path, PathBuf},
};

use crate::{
    Result, invalid,
    protocol::{CAPTURE_MARKER, PLAYLIST_MARKER, valid_slug},
    storage::{Playlist, Spot},
};

pub const GENERATED_HEADER: &str = "// Generated by Utilizer. Do not edit.";
pub const OUTPUT_DIRECTORY: &str = "console_utilizer_rust";

#[derive(Debug)]
pub struct CfgFile {
    pub filename: String,
    pub content: String,
}

/// Deliberately no navigation/binds: output the ordered positions and the
/// existing echo/getpos capture protocol only.
pub fn render(playlist: &Playlist, spots: &[Spot]) -> Result<Vec<CfgFile>> {
    if playlist.id <= 0 || !valid_slug(&playlist.slug) {
        return Err(invalid("Invalid playlist").into());
    }
    let mut content = format!(
        "{GENERATED_HEADER}\nsv_cheats 1\necholn \"{PLAYLIST_MARKER} {}\"\n",
        playlist.slug
    );
    let mut previous = 0;
    for spot in spots {
        if spot.playlist_id != playlist.id || spot.ordinal <= previous || !spot.position.is_valid()
        {
            return Err(invalid(
                "Spots must belong to the playlist and have valid ordered positions",
            )
            .into());
        }
        previous = spot.ordinal;
        let description: String = spot
            .description
            .chars()
            .map(|c| if c.is_control() { ' ' } else { c })
            .collect();
        content.push_str(&format!(
            "// {}: {description}\n{}\n",
            spot.ordinal,
            spot.position.command()
        ));
    }
    Ok(vec![
        CfgFile {
            filename: format!("playlist_{}.cfg", playlist.id),
            content,
        },
        CfgFile {
            filename: "ut_save.cfg".into(),
            content: format!(
                "{GENERATED_HEADER}\nsv_cheats 1\necholn \"{CAPTURE_MARKER}\"\ngetpos\n"
            ),
        },
    ])
}

/// Practice player files are generated only by an explicit browser action.
pub fn render_player(
    playlist: &Playlist,
    spots: &[Spot],
    selected: Option<i64>,
) -> Result<Vec<CfgFile>> {
    let mut files = render(playlist, spots)?;
    let selected = match selected {
        Some(id) => Some(
            spots
                .iter()
                .find(|s| s.id == id)
                .ok_or_else(|| invalid("Spot does not belong to this playlist"))?,
        ),
        None => spots.first(),
    };
    let exec = |id| format!("exec {OUTPUT_DIRECTORY}/spot_{id}");
    for (index, spot) in spots.iter().enumerate() {
        let next = &spots[(index + 1) % spots.len()];
        let previous = &spots[(index + spots.len() - 1) % spots.len()];
        files.push(CfgFile {
            filename: format!("spot_{}.cfg", spot.id),
            content: format!("{GENERATED_HEADER}\nsv_cheats 1\necholn \"{PLAYLIST_MARKER} {}\"\nalias ut_next \"{}\"\nalias ut_prev \"{}\"\n{}\n", playlist.slug, exec(next.id), exec(previous.id), spot.position.command()),
        });
    }
    let current = selected
        .map(|s| exec(s.id))
        .unwrap_or_else(|| "echoln \"Utilizer: capture and accept a spot first\"".into());
    files[0].content = format!(
        "{GENERATED_HEADER}\necholn \"{PLAYLIST_MARKER} {}\"\n{current}\n",
        playlist.slug
    );
    files.push(CfgFile {
        filename: "current.cfg".into(),
        content: format!(
            "{GENERATED_HEADER}\necholn \"{PLAYLIST_MARKER} {}\"\n{current}\n",
            playlist.slug
        ),
    });
    files.push(CfgFile {
        filename: "start.cfg".into(),
        content: format!("{GENERATED_HEADER}\nsv_cheats 1\nalias ut_save \"exec {OUTPUT_DIRECTORY}/ut_save\"\nalias ut_current \"exec {OUTPUT_DIRECTORY}/current\"\nalias ut_next ut_current\nalias ut_prev ut_current\nbind RIGHTARROW ut_next\nbind LEFTARROW ut_prev\nbind UPARROW ut_current\nbind F6 ut_save\nexec {OUTPUT_DIRECTORY}/current\n"),
    });
    Ok(files)
}

/// The caller explicitly supplies a validated CS2 cfg root. No startup writes.
pub fn export(cfg_root: &Path, files: &[CfgFile]) -> Result<Vec<PathBuf>> {
    let cfg_root = cfg_root.canonicalize()?;
    if !cfg_root.is_dir() {
        return Err(invalid("CS2 cfg root is not a directory").into());
    }
    let output = cfg_root.join(OUTPUT_DIRECTORY);
    match fs::create_dir(&output) {
        Ok(()) => {}
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
        Err(error) => return Err(error.into()),
    }
    let meta = fs::symlink_metadata(&output)?;
    if !meta.is_dir() || is_link(&meta) {
        return Err(invalid("Export directory must be a real directory, not a link").into());
    }
    // Preflight all targets before changing any files.
    let mut paths = Vec::new();
    for file in files {
        let mut components = Path::new(&file.filename).components();
        if !matches!(components.next(), Some(Component::Normal(_)))
            || components.next().is_some()
            || file.filename.contains([':', '/', '\\'])
            || !file.filename.ends_with(".cfg")
            || !file.content.starts_with(&format!("{GENERATED_HEADER}\n"))
        {
            return Err(invalid("Invalid generated cfg file").into());
        }
        let target = output.join(&file.filename);
        match fs::symlink_metadata(&target) {
            Ok(meta) => {
                if !meta.is_file()
                    || is_link(&meta)
                    || fs::read(&target)?.split(|b| *b == b'\n').next()
                        != Some(GENERATED_HEADER.as_bytes())
                {
                    return Err(invalid(format!(
                        "Refusing to overwrite unrelated file: {}",
                        target.display()
                    ))
                    .into());
                }
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(error) => return Err(error.into()),
        }
        paths.push(target);
    }
    for (file, target) in files.iter().zip(&paths) {
        // Unique, exclusively created staging files avoid stale-name conflicts
        // after a crash. Drop cleans up unsuccessful writes automatically.
        let mut staging = tempfile::NamedTempFile::new_in(&output)?;
        staging.write_all(file.content.as_bytes())?;
        staging.as_file().sync_all()?;
        staging.persist(target).map_err(|error| error.error)?;
    }
    Ok(paths)
}

fn is_link(metadata: &fs::Metadata) -> bool {
    #[cfg(windows)]
    {
        use std::os::windows::fs::MetadataExt;
        metadata.file_attributes() & 0x400 != 0 // Includes directory junctions.
    }
    #[cfg(not(windows))]
    {
        metadata.file_type().is_symlink()
    }
}
